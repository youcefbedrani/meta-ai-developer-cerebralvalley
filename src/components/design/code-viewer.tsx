"use client";

import { ArrowLeft, Copy, Download, File, FolderOpen, MousePointerClick, Zap } from "lucide-react";
import Link from "next/link";
import { useMemo, useState } from "react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { cn } from "@/lib/utils";

/** Browse the generated codebase, download it, or run it in the browser on StackBlitz. */
export function CodeViewer({ projectId, name, files, order, generatedAt }: { projectId: string; name: string; files: Record<string, string>; order: string[]; generatedAt: string }) {
  const [path, setPath] = useState(order.find((p) => p.endsWith("page.tsx")) ?? order[0]);
  const groups = useMemo(() => {
    const out: Record<string, string[]> = {};
    for (const p of order) {
      const dir = p.includes("/") ? p.slice(0, p.lastIndexOf("/")) : "";
      (out[dir] ??= []).push(p);
    }
    return Object.entries(out);
  }, [order]);
  const code = files[path] ?? "";
  const lines = code.split("\n").length;
  const base = `/app/projects/${projectId}/design`;

  return (
    <div className="space-y-3">
      <div className="surface flex flex-wrap items-center gap-2 p-3">
        <Link href={base} className="inline-flex items-center gap-1 rounded-lg px-2 py-1 text-sm text-muted-foreground hover:bg-muted hover:text-foreground"><ArrowLeft className="size-4" /> Design</Link>
        <span className="mx-1 h-5 w-px bg-border" />
        <div className="min-w-0">
          <p className="text-sm font-medium">{name}: MVP code</p>
          <p className="text-xs text-muted-foreground">Next.js + Tailwind · {order.length} files · generated by Muse Spark {new Date(generatedAt).toLocaleString()}</p>
        </div>
        <div className="ml-auto flex flex-wrap items-center gap-2">
          <Link href={`${base}/prototype`} className="inline-flex h-9 items-center gap-1.5 rounded-[10px] border border-border px-3 text-sm hover:bg-muted"><MousePointerClick className="size-4" /> Prototype</Link>
          <a href={`${base}/code/download`} className="inline-flex h-9 items-center gap-1.5 rounded-[10px] border border-border px-3 text-sm hover:bg-muted"><Download className="size-4" /> Download .zip</a>
          {/* StackBlitz's POST API: the files go to StackBlitz only when the founder clicks. */}
          <form action="https://stackblitz.com/run?file=README.md" method="post" target="_blank">
            <input type="hidden" name="project[title]" value={name} />
            <input type="hidden" name="project[description]" value={`${name}: MVP generated with Startum`} />
            <input type="hidden" name="project[template]" value="node" />
            {order.map((p) => <input key={p} type="hidden" name={`project[files][${p}]`} value={files[p]} />)}
            <Button type="submit" variant="gradient" className="h-9 px-4"><Zap /> Run it on StackBlitz</Button>
          </form>
        </div>
      </div>

      <div className="grid gap-3 lg:grid-cols-[260px_1fr]">
        <nav aria-label="Files" className="surface max-h-[75vh] overflow-auto p-2 text-sm">
          {groups.map(([dir, paths]) => (
            <div key={dir || "root"} className="mb-2">
              {dir ? <p className="flex items-center gap-1.5 px-2 py-1 text-xs text-muted-foreground"><FolderOpen className="size-3.5" /> {dir}</p> : null}
              <ul>
                {paths.map((p) => (
                  <li key={p}>
                    <button type="button" onClick={() => setPath(p)} className={cn("flex w-full items-center gap-1.5 rounded-md py-1 pr-2 text-left", dir ? "pl-6" : "pl-2", p === path ? "bg-primary/10 font-medium text-primary" : "hover:bg-muted")}>
                      <File className="size-3.5 shrink-0 opacity-60" /> <span className="truncate">{p.slice(dir ? dir.length + 1 : 0)}</span>
                    </button>
                  </li>
                ))}
              </ul>
            </div>
          ))}
        </nav>
        <div className="surface flex min-w-0 flex-col overflow-hidden">
          <div className="flex items-center gap-2 border-b border-border px-3 py-2 text-xs">
            <code className="truncate font-medium">{path}</code>
            <span className="text-muted-foreground">{lines} lines</span>
            <button type="button" className="ml-auto inline-flex items-center gap-1 rounded-md px-2 py-1 hover:bg-muted" onClick={() => navigator.clipboard.writeText(code).then(() => toast.success("Copied"), () => toast.error("Couldn't copy"))}><Copy className="size-3.5" /> Copy</button>
          </div>
          <pre className="max-h-[70vh] overflow-auto bg-neutral-950 p-4 text-[12.5px] leading-relaxed text-neutral-100"><code>{code}</code></pre>
        </div>
      </div>
    </div>
  );
}
