import { PLAYBOOK_STAGE_LABEL, type LaunchPlaybook, type RevenueMath } from "@/lib/validation/launch-playbook";

const money = (n: number) => `$${n.toLocaleString("en-US")}`;
const list = (items: string[]) => items.map((i) => `- ${i}`).join("\n");

/** The launch playbook as a Markdown document founders can keep, share or paste into other tools. */
export function playbookMarkdown(projectName: string, p: LaunchPlaybook, math: RevenueMath, generatedAt: Date): string {
  const s = p.sales;
  return [
    `# ${projectName}: launch playbook`,
    `_Generated by Startum on ${generatedAt.toISOString().slice(0, 10)}. Targets, churn and costs are assumptions to test._`,
    `## Strategy\n${p.summary}`,
    `**North star (90 days):** ${p.northStar.goal}. Metric: ${p.northStar.metric}. ${p.northStar.why}`,
    `## Roadmap`,
    ...p.stages.map((st, i) =>
      [
        `### ${i + 1}. ${PLAYBOOK_STAGE_LABEL[st.stage]} (${st.timeframe})`,
        st.goal,
        `**Move on when:**\n${list(st.exitCriteria)}`,
        `**Tasks:**\n${st.tasks.map((t) => `- [ ] **${t.title}** (${t.hours} h): ${t.detail}`).join("\n")}`,
        st.risks.length ? `**Risks:**\n${list(st.risks)}` : "",
      ].filter(Boolean).join("\n\n"),
    ),
    `## Sales playbook`,
    `**Motion:** ${s.motion.replace("_", " ")}. ${s.motionWhy}`,
    `### Ideal customer\n- **Company:** ${s.icp.company}\n- **Buyer:** ${s.icp.buyer}\n- **User:** ${s.icp.user}\n\n**Buying triggers:**\n${list(s.icp.triggers)}${s.icp.disqualifiers.length ? `\n\n**Walk away from:**\n${list(s.icp.disqualifiers)}` : ""}`,
    `### Prospecting\n**Where to find them:**\n${list(s.prospecting.whereToFind)}\n\n**List criteria:**\n${list(s.prospecting.listCriteria)}\n\n**Daily routine:** ${s.prospecting.dailyRoutine}`,
    `### Outreach sequence\n${s.outreachSequence.map((o) => `**Day ${o.day} · ${o.channel}** (${o.goal})\n\n> ${o.message.replace(/\n/g, "\n> ")}`).join("\n\n")}`,
    `### Discovery questions\n${s.discoveryQuestions.map((q, i) => `${i + 1}. ${q}`).join("\n")}`,
    `### Demo flow\n${s.demoFlow.map((d, i) => `${i + 1}. **${d.step}**: show ${d.show}. Say: "${d.say}"`).join("\n")}`,
    `### Objections\n${s.objections.map((o) => `- **${o.objection}**\n  ${o.response}\n  _Basis: ${o.basis.replace("_", " ")}. ${o.evidence}_`).join("\n")}`,
    `### Closing\n- **Founding offer:** ${s.closing.foundingOffer}\n- **The ask:** ${s.closing.ask}\n- **Follow-up:** ${s.closing.followUp}`,
    `### Pipeline\n| Stage | Definition | Next action |\n|---|---|---|\n${s.pipeline.map((st) => `| ${st.stage} | ${st.definition} | ${st.nextAction} |`).join("\n")}`,
    `## Metrics`,
    `**Activation moment:** ${p.metrics.activationMoment}`,
    `| Funnel stage | Definition | How to measure | Target (assumption) |\n|---|---|---|---|\n${p.metrics.funnel.map((f) => `| ${f.stage} | ${f.definition} | ${f.howToMeasure} | ${f.targetAssumption} |`).join("\n")}`,
    `**Weekly dashboard:**\n${list(p.metrics.weeklyDashboard)}`,
    `### Unit economics (computed from ${math.priceSource === "business_model" ? "your business model" : "an assumed price"})\n- Price: ${money(math.priceMonthly)}/month\n- Assumed monthly churn: ${math.churnPct}%\n- Lifetime value: about ${money(math.ltv)}\n- Spend at most about ${money(math.cacCeiling)} to win a customer (a third of LTV)\n${math.milestones.map((m) => `- ${money(m.mrr)} MRR = ${m.customers} customers`).join("\n")}\n\n${p.metrics.unitEconomicsNotes}`,
    `## Retention\n**Onboarding to the activation moment:**\n${p.retention.onboarding.map((o, i) => `${i + 1}. ${o}`).join("\n")}\n\n**Churn signals:**\n${list(p.retention.churnSignals)}\n\n**Save actions:**\n${list(p.retention.saveActions)}`,
    `## Pricing tactics\n${list(p.pricingTactics)}`,
    `## Build plan`,
    p.build.sprints.map((sp) => `### Week ${sp.week}: ${sp.focus}\n${list(sp.deliverables)}\n\n_Done when:_ ${sp.doneWhen}`).join("\n\n"),
    `### Launch infrastructure\n${p.build.launchInfra.map((x) => `- [ ] ${x}`).join("\n")}`,
    `### Prompts for your AI coding tool\n${p.build.aiCodingPrompts.map((x) => `#### ${x.title}\n\n\`\`\`\n${x.prompt}\n\`\`\``).join("\n\n")}`,
  ].join("\n\n") + "\n";
}
